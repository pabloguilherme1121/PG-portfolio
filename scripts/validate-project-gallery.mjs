import { chromium } from "playwright";

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ reducedMotion: "reduce", viewport: { width: 390, height: 844 } });
await page.goto("http://127.0.0.1:3000/", { waitUntil: "networkidle" });
await page.locator("#projetos").scrollIntoViewIfNeeded();

const filters = page.locator("#projetos button[aria-pressed]");
const labels = await filters.allTextContents();
const todosButton = filters.first();
await todosButton.focus();
const focusVisible = await todosButton.evaluate((element) => {
  const style = getComputedStyle(element);
  return style.outlineStyle !== "none" || style.boxShadow !== "none";
});

await page.keyboard.press("Tab");
const focusMovedByTab = await page.evaluate(() => document.activeElement?.textContent?.trim() === "Vídeo");
const droneButton = page.getByRole("button", { name: "Drone", exact: true }).first();
await droneButton.focus();
await page.keyboard.press("Enter");
const transitionClassDuringChange = await page.locator("#projetos .project-gallery-stage").getAttribute("class");
const focusedDuringTransition = await page.evaluate(() => document.activeElement?.textContent?.trim() === "Drone");
await page.waitForTimeout(260);
const transitionClassAfterChange = await page.locator("#projetos .project-gallery-stage").getAttribute("class");
const focusPreservedAfterTransition = await page.evaluate(() => document.activeElement?.textContent?.trim() === "Drone");
const selectedState = await droneButton.getAttribute("aria-pressed");
const visibleCards = await page.locator("#projetos .project-gallery-card").count();
const compactToggle = page.locator('#projetos button[aria-label*="visualização"]').first();
await compactToggle.focus();
await page.keyboard.press("Enter");
const compactState = await compactToggle.getAttribute("aria-pressed");
const compactToggleLabel = await compactToggle.getAttribute("aria-label");
const compactCardClass = await page.locator("#projetos .project-gallery-card").first().getAttribute("class");
const compactFocusPreserved = await page.evaluate(() => document.activeElement?.textContent?.includes("modo compacto") ?? false);
const searchInput = page.locator('#projetos input[type="search"]');
await searchInput.fill("cha");
const suggestionCount = await page.locator('#project-search-suggestions [role="option"]').count();
const suggestionsExpanded = await searchInput.getAttribute("aria-expanded");
await searchInput.press("ArrowDown");
const activeSuggestionId = await searchInput.getAttribute("aria-activedescendant");
await searchInput.press("Enter");
const keyboardSuggestionValue = await searchInput.inputValue();
const keyboardSuggestionResultCount = await page.locator("#projetos .project-gallery-card").count();
await searchInput.fill("cele");
const descriptionSuggestion = page.locator('#project-search-suggestions [role="option"]', { hasText: "celebração" });
await descriptionSuggestion.click();
const clickSuggestionValue = await searchInput.inputValue();
const clickSuggestionResultCount = await page.locator("#projetos .project-gallery-card").count();
await searchInput.fill("Eloise");
const searchResultCount = await page.locator("#projetos .project-gallery-card").count();
const searchFeedback = await page.locator("#project-search-feedback").textContent();
await searchInput.fill("inexistente");
const emptySearchMessage = await page.locator("#projetos .project-gallery-empty").textContent();
await page.getByRole("button", { name: "Limpar busca de trabalhos" }).click();
const clearedSearchValue = await searchInput.inputValue();
const clearedSearchCount = await page.locator("#projetos .project-gallery-card").count();
const todosFilter = page.getByRole("button", { name: "Todos", exact: true }).first();
await todosFilter.click();
await page.waitForTimeout(260);
await searchInput.fill("inte");
const technologySuggestionCount = await page.locator('#project-search-suggestions [role="option"]').count();
await searchInput.press("ArrowDown");
await searchInput.press("Enter");
const technologySuggestionValue = await searchInput.inputValue();
const technologySearchCount = await page.locator("#projetos .project-gallery-card").count();
await searchInput.fill("celebração");
const descriptionSearchCount = await page.locator("#projetos .project-gallery-card").count();
const reducedMotion = await page.evaluate(() => window.matchMedia("(prefers-reduced-motion: reduce)").matches);

console.log(JSON.stringify({ labels, focusVisible, focusMovedByTab, focusedDuringTransition, focusPreservedAfterTransition, selectedState, visibleCards, compactState, compactToggleLabel, compactCardClass, compactFocusPreserved, suggestionCount, suggestionsExpanded, activeSuggestionId, keyboardSuggestionValue, keyboardSuggestionResultCount, clickSuggestionValue, clickSuggestionResultCount, searchResultCount, searchFeedback, emptySearchMessage, clearedSearchValue, clearedSearchCount, technologySuggestionCount, technologySuggestionValue, technologySearchCount, descriptionSearchCount, reducedMotion, transitionClassDuringChange, transitionClassAfterChange }));
await browser.close();
